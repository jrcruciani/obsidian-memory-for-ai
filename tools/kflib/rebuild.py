GENERATED_BANNER_RE = re.compile(
    r"\A<!-- DO NOT EDIT: generated by kf rebuild \| (?:profile=[a-z0-9_-]+ \| )?source_digest=(sha256:[0-9a-f]{64}) \| content_sha256=(sha256:[0-9a-f]{64}) -->\n"
)


def _wrap_generated(title: str, body: str, source_digest: str) -> str:
    payload = f"# {title}\n\n> **NON-EDITABLE DERIVED VIEW** — Regenerate with `python3 tools/kf.py rebuild`. Hand-edits fail `kf.py lint --strict`.\n\n{body.strip()}\n"
    content_hash = "sha256:" + hashlib.sha256(payload.encode("utf-8")).hexdigest()
    banner = f"<!-- DO NOT EDIT: generated by kf rebuild | source_digest={source_digest} | content_sha256={content_hash} -->\n"
    return banner + payload


def build_all_views(root: Path) -> dict[str, str]:
    ref = today()
    digest = canonical_source_digest(root, ref)
    files: dict[str, str] = {}

    cfg = load_yaml_file(root / "factory/schema/bootstrap.yaml")
    profiles = (cfg.get("profiles") or {"default": {}, "executor": {}, "curator": {}}).keys()
    files["_generated/views/bootstrap.md"] = build_bootstrap(root, profile="default")
    for prof in sorted(profiles):
        if prof != "default":
            files[f"_generated/views/bootstrap-{prof}.md"] = build_bootstrap(root, profile=prof)

    entities = load_entities(root)
    active_facts = [(rel_path(p, root), fm) for p, fm, _ in scan_records(root, "knowledge/facts", "fact") if is_fact_visible(fm, ref)]
    active_skills = [(rel_path(p, root), fm) for p, fm, _ in scan_records(root, "knowledge/skills", "skill") if is_active_head(fm)]
    active_guidance = [(rel_path(p, root), fm) for p, fm, _ in scan_records(root, "knowledge/guidance", "guidance") if is_active_head(fm)]
    decisions = [(rel_path(p, root), fm) for p, fm, _ in scan_records(root, "knowledge/decisions", "decision") if is_active_head(fm)]
    events = [(rel_path(p, root), fm) for p, fm, _ in scan_records(root, "knowledge/events", "event")]
    signals = [(rel_path(p, root), fm) for p, fm, _ in scan_records(root, "factory/signals", "signal")]
    proposals = [(rel_path(p, root), fm) for p, fm, _ in scan_records(root, "factory/proposals", "proposal")]
    receipts = [(rel_path(p, root), fm) for p, fm, _ in scan_records(root, "factory/receipts", "receipt")]

    # Catalog view
    cat_lines = [
        f"## Entities ({len(entities)})",
        *(
            [f"- **{e.get('display', eid)}** (`{eid}`, `{e.get('kind', 'entity')}`) — aliases: {', '.join(e.get('aliases') or []) or 'none'}" for eid, e in sorted(entities.items())]
            or ["_None._"]
        ),
        "",
        f"## Living Facts ({len(active_facts)})",
        *(
            [f"- `{fm['entity']}/{fm['predicate']}` = {render_scalar_inline(fm['value'])} (trust: `{fm['trust']}`, conf: `{fm.get('confidence')}`) — `{r}`" for r, fm in active_facts]
            or ["_None._"]
        ),
        "",
        f"## Living Skills ({len(active_skills)})",
        *(
            [f"- **{fm['title']}** (`{fm['slug']}`, v{fm['version']}, `{fm['domain']}`) — `{r}`" for r, fm in active_skills]
            or ["_None._"]
        ),
        "",
        f"## Living Guidance ({len(active_guidance)})",
        *(
            [f"- **[{fm['priority'].upper()}] {fm['title']}** (`{fm['domain']}` / `{fm['scope']}`): {fm['policy_rule']} — `{r}`" for r, fm in active_guidance]
            or ["_None._"]
        ),
        "",
        f"## Accepted Decisions ({len(decisions)})",
        *(
            [f"- **{fm['id']}** ({fm['decided_at']}): {fm['title']} — `{r}`" for r, fm in decisions]
            or ["_None._"]
        ),
    ]
    files["_generated/views/catalog.md"] = _wrap_generated("Knowledge Catalog", "\n".join(cat_lines), digest)

    # Factory queue view
    open_sigs = [(r, fm) for r, fm in signals if fm.get("status") in {"open", "proposed"}]
    open_props = [(r, fm) for r, fm in proposals if fm.get("status") != "published"]
    fq_lines = [
        f"## Open & Proposed Signals ({len(open_sigs)})",
        *(
            [f"- **{fm['id']}** [{fm['status']}/{fm['severity']}/{fm['kind']}] {fm['summary']} — `{r}`" for r, fm in open_sigs]
            or ["_No open signals._"]
        ),
        "",
        f"## Active Proposals ({len(open_props)})",
        *(
            [f"- **{fm['id']}** [{fm['status']}] {fm['title']} (proposer: `{fm['proposer_id']}`) — `{r}`" for r, fm in open_props]
            or ["_No pending proposals._"]
        ),
        "",
        f"## Recent Receipts ({len(receipts)})",
        *(
            [f"- **{fm['id']}** [{fm['mode']}/{fm['status']}] actor=`{fm['actor_id']}` files={len(fm.get('touched_files') or [])} — `{r}`" for r, fm in receipts[-15:]]
            or ["_No receipts yet._"]
        ),
    ]
    files["_generated/views/factory-queue.md"] = _wrap_generated("Knowledge Factory Queue", "\n".join(fq_lines), digest)

    # Stale view
    stale_rows = compute_stale_records(root)
    stale_lines = [f"- `{r}`: {reason}" for r, reason in stale_rows] or ["_No stale records as of " + ref.isoformat() + "._"]
    files["_generated/views/stale.md"] = _wrap_generated("Stale Knowledge Report", "\n".join(stale_lines), digest)

    # Conflicts & contradictions view
    conflict_sigs = [(r, fm) for r, fm in signals if fm.get("status") == "open" and fm.get("kind") in {"contradiction", "broken_reference"}]
    conf_lines = [f"- **{fm['id']}** [{fm['kind']}]: {fm['summary']} — `{r}`" for r, fm in conflict_sigs] or ["_No active contradictions or broken-reference signals._"]
    files["_generated/views/conflicts.md"] = _wrap_generated("Conflicts & Integrity Flags", "\n".join(conf_lines), digest)

    # Timeline view
    tl_entries: list[tuple[str, str]] = []
    for r, fm in events:
        d = parse_datetime(fm["occurred_at"]).date().isoformat()
        tl_entries.append((d, f"- **{d}** [event] {fm['summary']} (`{r}`)"))
    for r, fm in decisions:
        d = str(fm["decided_at"])
        tl_entries.append((d, f"- **{d}** [decision] {fm['id']}: {fm['title']} (`{r}`)"))
    for r, fm in receipts:
        d = parse_datetime(fm.get("committed_at") or fm["created_at"]).date().isoformat()
        tl_entries.append((d, f"- **{d}** [receipt:{fm['mode']}] {fm['id']} by `{fm['actor_id']}` (`{r}`)"))
    tl_entries.sort(key=lambda item: item[0], reverse=True)
    tl_body = "\n".join(line for _, line in tl_entries) or "_Timeline is empty._"
    files["_generated/views/timeline.md"] = _wrap_generated("Chronological Timeline", tl_body, digest)

    # By-entity dossiers
    for eid, ent in sorted(entities.items()):
        ent_facts = [(r, fm) for r, fm in active_facts if fm.get("entity") == eid]
        ent_events = [(r, fm) for r, fm in events if eid in (fm.get("entities") or [])]
        ent_skills = [(r, fm) for r, fm in active_skills if eid in (fm.get("entities") or [])]
        ent_decs = [(r, fm) for r, fm in decisions if eid in (fm.get("entities") or [])]
        dossier = [
            f"Kind: `{ent.get('kind', 'entity')}` | Aliases: {', '.join(ent.get('aliases') or []) or 'none'}",
            "",
            "## Current Facts",
            *([f"- **{fm['predicate']}**: {render_scalar_inline(fm['value'])} (`{r}`)" for r, fm in ent_facts] or ["_None._"]),
            "",
            "## Related Skills",
            *([f"- **{fm['title']}** (`{r}`)" for r, fm in ent_skills] or ["_None._"]),
            "",
            "## Related Decisions",
            *([f"- **{fm['id']}**: {fm['title']} (`{r}`)" for r, fm in ent_decs] or ["_None._"]),
            "",
            "## Events",
            *([f"- {str(fm['occurred_at'])[:10]}: {fm['summary']} (`{r}`)" for r, fm in ent_events] or ["_None._"]),
        ]
        files[f"_generated/views/by-entity/{eid}.md"] = _wrap_generated(
            f"Entity Dossier: {ent.get('display', eid)} ({eid})",
            "\n".join(dossier),
            digest,
        )

    return files


def build_lexical_entries(root: Path) -> list[dict[str, str]]:
    ref = today()
    entries: list[dict[str, str]] = []
    for p, fm, body in scan_records(root, "knowledge/facts", "fact"):
        if not is_fact_visible(fm, ref):
            continue
        entries.append({
            "kind": "fact",
            "id": str(fm["id"]),
            "subject": f"{fm['entity']}/{fm['predicate']}",
            "summary": render_scalar_inline(fm.get("value")),
            "path": rel_path(p, root),
            "body_excerpt": " ".join(body.split())[:160],
        })
    for p, fm, body in scan_records(root, "knowledge/skills", "skill"):
        if not is_active_head(fm):
            continue
        entries.append({
            "kind": "skill",
            "id": str(fm["id"]),
            "subject": f"{fm['slug']} ({fm['domain']})",
            "summary": f"{fm['title']} | triggers: {', '.join(str(t) for t in (fm.get('triggers') or []))}",
            "path": rel_path(p, root),
            "body_excerpt": " ".join(body.split())[:160],
        })
    for p, fm, body in scan_records(root, "knowledge/guidance", "guidance"):
        if not is_active_head(fm):
            continue
        entries.append({
            "kind": "guidance",
            "id": str(fm["id"]),
            "subject": f"{fm['slug']} ({fm['domain']}/{fm['scope']})",
            "summary": f"{fm['title']}: {fm['policy_rule']}",
            "path": rel_path(p, root),
            "body_excerpt": " ".join(body.split())[:160],
        })
    for p, fm, body in scan_records(root, "knowledge/decisions", "decision"):
        if not is_active_head(fm):
            continue
        entries.append({
            "kind": "decision",
            "id": str(fm["id"]),
            "subject": f"{fm['id']} ({fm['domain']})",
            "summary": f"{fm['title']}: {fm['summary']}",
            "path": rel_path(p, root),
            "body_excerpt": " ".join(body.split())[:160],
        })
    entries.sort(key=lambda e: (e["kind"], e["path"]))
    return entries


def compute_graph_edges(root: Path) -> list[tuple[str, str, str, str]]:
    """Return sorted tuples (source_node, relation, target_node, evidence_path)."""
    entities = load_entities(root)
    alias_to_id: dict[str, str] = {}
    for eid, ent in entities.items():
        for name in [eid, ent.get("display", ""), *(ent.get("aliases") or [])]:
            if isinstance(name, str) and name.strip():
                alias_to_id[fold_text(name)] = eid

    ref = today()
    edges: set[tuple[str, str, str, str]] = set()
    for p, fm, body in scan_records(root, "knowledge/facts", "fact"):
        if not is_fact_visible(fm, ref):
            continue
        r = rel_path(p, root)
        src = str(fm["entity"])
        pred = str(fm["predicate"])
        val = fm.get("value")
        candidates = val if isinstance(val, list) else [val]
        for cand in candidates:
            if isinstance(cand, str):
                target_ent = alias_to_id.get(fold_text(cand))
                if target_ent and target_ent != src:
                    edges.add((src, pred, target_ent, r))
        for wl in WIKILINK_RE.findall(body):
            stem = Path(wl.strip()).stem
            if stem in entities and stem != src:
                edges.add((src, "wikilink", stem, r))

    for folder, rtype in (("knowledge/skills", "skill"), ("knowledge/guidance", "guidance"), ("knowledge/decisions", "decision")):
        for p, fm, _ in scan_records(root, folder, rtype):
            if not is_active_head(fm):
                continue
            r = rel_path(p, root)
            rec_id = str(fm["id"])
            for ent in fm.get("entities") or []:
                if ent in entities:
                    edges.add((ent, f"has_{rtype}", rec_id, r))

    return sorted(edges)


def build_all_indexes(root: Path) -> dict[str, str]:
    ref = today()
    digest = canonical_source_digest(root, ref)
    entities = load_entities(root)

    lex_lines = ["## Entity Aliases", ""]
    if entities:
        for eid, ent in sorted(entities.items()):
            lex_lines.append(f"- `{eid}` | display: `{ent.get('display', eid)}` | aliases: `{', '.join(ent.get('aliases') or [])}`")
    else:
        lex_lines.append("_No entities._")
    lex_lines.extend(["", "## Living Records", ""])
    lex_entries = build_lexical_entries(root)
    if lex_entries:
        for item in lex_entries:
            lex_lines.append(f"- [{item['kind']}] `{item['subject']}` :: {item['summary']} :: `{item['path']}`")
    else:
        lex_lines.append("_No living records._")

    edges = compute_graph_edges(root)
    graph_lines = ["## Edges", ""]
    if edges:
        for src, rel_name, dst, ev in edges:
            graph_lines.append(f"- `{src}` --[{rel_name}]--> `{dst}` (`{ev}`)")
    else:
        graph_lines.append("_No graph edges._")

    return {
        "_generated/indexes/lexical.md": _wrap_generated("Lexical Index", "\n".join(lex_lines), digest),
        "_generated/indexes/graph.md": _wrap_generated("Relationship Graph Index", "\n".join(graph_lines), digest),
    }


def rebuild_all(root: Path, *, views_only: bool = False, indexes_only: bool = False) -> list[str]:
    expected: dict[str, str] = {}
    if not indexes_only:
        expected.update(build_all_views(root))
    if not views_only:
        expected.update(build_all_indexes(root))

    # Remove stale files inside rebuilt directories so deleted entities don't linger
    if not indexes_only:
        views_dir = root / "_generated/views"
        if views_dir.exists():
            for existing in sorted(views_dir.rglob("*.md")):
                if rel_path(existing, root) not in expected:
                    existing.unlink()
    if not views_only:
        idx_dir = root / "_generated/indexes"
        if idx_dir.exists():
            for existing in sorted(idx_dir.rglob("*.md")):
                if rel_path(existing, root) not in expected:
                    existing.unlink()

    written: list[str] = []
    for rel, content in sorted(expected.items()):
        atomic_write_text(root / rel, content)
        written.append(rel)
    return written


def verify_generated_integrity(root: Path) -> list[tuple[str, str]]:
    """Verify that _generated/ matches canonical state and has not been hand-edited."""
    issues: list[tuple[str, str]] = []
    expected: dict[str, str] = {}
    expected.update(build_all_views(root))
    expected.update(build_all_indexes(root))

    gen_root = root / "_generated"
    if not gen_root.exists():
        return [("_generated", "missing _generated directory; run `python3 tools/kf.py rebuild`")]

    actual_files = {rel_path(p, root): p for p in sorted(gen_root.rglob("*.md"))}
    for rel, exp_content in sorted(expected.items()):
        if rel not in actual_files:
            issues.append((rel, "missing generated artifact; run `python3 tools/kf.py rebuild`"))
            continue
        act_content = actual_files[rel].read_text(encoding="utf-8")
        m = GENERATED_BANNER_RE.match(act_content)
        if not m:
            issues.append((rel, "generated artifact banner missing or hand-edited"))
            continue
        if act_content != exp_content:
            recorded_content_sha = m.group(2)
            if recorded_content_sha:
                body_after_banner = act_content[m.end():]
                actual_sha = "sha256:" + hashlib.sha256(body_after_banner.encode("utf-8")).hexdigest()
                if actual_sha != recorded_content_sha:
                    issues.append((rel, "generated artifact was hand-edited (content_sha256 mismatch); never edit _generated/"))
                    continue
            issues.append((rel, "generated artifact is stale relative to canonical knowledge/factory state; run `python3 tools/kf.py rebuild`"))

    for rel in sorted(set(actual_files.keys()) - set(expected.keys())):
        issues.append((rel, "unexpected extra file inside _generated/; run `python3 tools/kf.py rebuild`"))
    return issues
